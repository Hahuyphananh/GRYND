// ── Template interpolation helper ───────────────────────────────────────
// Many translation strings include placeholders like "{wager}", "{name}",
// "{round}", etc. This helper walks the resolved string and substitutes
// each `{key}` occurrence with the matching value from `params`. Missing
// keys are left intact so the call site can spot the bug (the
// placeholder surfaces in the UI instead of disappearing silently).
const interpolate = (template, params) => {
  if (!params || typeof params !== "object") return template;
  if (typeof template !== "string") return template;
  return template.replace(/\{(\w+)\}/g, (m, k) =>
    params[k] !== undefined ? String(params[k]) : m
  );
};

export const t = (lang, key, fallbackOrParams) => {
  const keys = key.split(".");
  const resolve = (obj) => keys.reduce((acc, k) => acc?.[k], obj);
  // Try dotted-path navigation first (canonical nested shape).
  let raw =
    resolve(APP_TEXT_TRANSLATIONS?.[lang]) ||
    resolve(APP_TEXT_TRANSLATIONS?.en);
  // Then try the literal flat-string key against every top-level
  // child of the locale bundle. This rescues any future block that
  // inherits the historical merge-script flatten bug (`{
  // "lobby.title": "..." }`) without crashing the consumer.
  if (raw == null) {
    const langRoot = APP_TEXT_TRANSLATIONS?.[lang];
    const enRoot = APP_TEXT_TRANSLATIONS?.en;
    for (const root of [langRoot, enRoot]) {
      if (!root) continue;
      for (const child of Object.values(root)) {
        if (
          child &&
          typeof child === "object" &&
          Object.prototype.hasOwnProperty.call(child, key)
        ) {
          raw = child[key];
          break;
        }
      }
      if (raw != null) break;
    }
  }
  if (raw == null) {
    // The third argument is dual-purpose: callers historically pass
    // either an English fallback string OR an interpolation params
    // object (`t("foo.bar", "fallback")` vs `t("foo.bar", { n: 1 })`).
    // Use the string fallback if provided; otherwise surface the raw
    // key so QA can spot the gap instead of the user seeing a blank.
    raw = typeof fallbackOrParams === "string" ? fallbackOrParams : key;
  }
  const params =
    fallbackOrParams && typeof fallbackOrParams === "object"
      ? fallbackOrParams
      : undefined;
  return interpolate(raw, params);
};
