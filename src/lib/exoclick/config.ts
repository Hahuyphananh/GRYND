// src/lib/exoclick/config.ts
//
// THE ONE PLACE THE EXOCLICK BANNER IS CONFIGURED.
//
// ── ISOLATION ─────────────────────────────────────────────────────────────
//
// This module is independent of the HilltopAds banner (src/lib/hilltop/*) and
// of AdSense (src/lib/ads.ts). It reads only EXOCLICK_* variables, and neither
// of the other providers imports it. Switching ExoClick off cannot affect
// Hilltop or AdSense, and switching either of those off cannot affect this.
//
// ── THE PROVIDER'S ASYNCHRONOUS BANNER TAG ────────────────────────────────
//
// ExoClick's publisher dashboard generates an asynchronous banner tag of this
// shape (published at
// https://docs.exoclick.com/publishers/sites-and-zones/create-zone):
//
//   <script async type="application/javascript"
//     src="a.magsrv.com/ad-provider.js"></script>
//   <ins class="<ZONE_CLASS>" data-zoneid="<ZONE_ID>"></ins>
//   <script>(AdProvider = window.AdProvider || []).push({"serve": {}});</script>
//
// The two values this repository CANNOT invent are the zone id and the `<ins>`
// class token: both are generated per zone in the publisher account, and the
// class token differs between zone versions. So neither has a default — the
// banner renders NOTHING until both are supplied through configuration.
//
// The ad-provider URL is the same for every publisher and is the only default
// here. It can still be overridden (a dashboard can hand out a protocol-
// relative URL), but only on an approved ExoClick host over https.
//
// ── WHY THIS ONLY SUPPORTS CLASSIC BANNERS ────────────────────────────────
//
// The `class` token is generated for ONE zone type. A banner zone produces a
// conventional in-flow banner; sticky banners, direct links, popunders,
// in-page push and interstitials are separate zone types with their own tags.
// GRYND does not ship any of those, and this integration never calls a
// provider API that could request one. Choosing a banner zone is an operator
// step documented in docs/exoclick-deployment.md.
//
// ── CONFIGURATION (exact names) ───────────────────────────────────────────
//
//   NEXT_PUBLIC_EXOCLICK_ENABLED              build-time switch. Opt-in:
//                                             "true"/"1" only.
//   EXOCLICK_ENABLED                          server, read per request. Same
//                                             opt-in rule.
//   NEXT_PUBLIC_EXOCLICK_SCRIPT_URL           optional override for the
//                                             provider loader. Must be https
//                                             on an approved host, with no
//                                             credentials.
//   NEXT_PUBLIC_EXOCLICK_INS_CLASS            REQUIRED. The `<ins>` class token
//                                             generated by the dashboard.
//   NEXT_PUBLIC_EXOCLICK_INS_CLASS_<PLACEMENT> optional per-placement token
//                                             when zones use different classes.
//   NEXT_PUBLIC_EXOCLICK_ZONE_<PLACEMENT>     REQUIRED. The numeric zone id.
//   NEXT_PUBLIC_EXOCLICK_BANNER_SIZE          optional: 300x250 (default),
//                                             728x90, or responsive.
//   NEXT_PUBLIC_EXOCLICK_BANNER_SIZE_<PLACEMENT> optional per-placement size.
//   NEXT_PUBLIC_EXOCLICK_REQUIRES_CONSENT     defaults to true. Set "false"
//                                             only for a deploy whose consent
//                                             basis does not require it.
//
// Everything is opt-in and fails closed: a missing zone, a missing class, a
// malformed URL or an unapproved placement renders nothing at all.

/** The documented asynchronous ad-provider loader. */
export const EXOCLICK_AD_PROVIDER_URL = "https://a.magsrv.com/ad-provider.js";

/** Hosts an override may use. Any `*.magsrv.com` / `*.exoclick.com` is allowed. */
export const EXOCLICK_PROVIDER_HOSTS = ["magsrv.com", "exoclick.com"] as const;

/** The container GRYND owns; the provider may only fill the `<ins>` inside it. */
export const EXOCLICK_CONTAINER_PREFIX = "grynd-exoclick-banner";

/** Marks the provider loader element, so a remount can never inject it twice. */
export const EXOCLICK_PROVIDER_ATTRIBUTE = "data-grynd-exoclick-provider";

/** Marks our own `<ins>` element, so a remount can never create a second one. */
export const EXOCLICK_INS_ATTRIBUTE = "data-grynd-exoclick-ins";

/** How long a blocked or unfilled request may hold the reserved area. */
export const EXOCLICK_READY_TIMEOUT_MS = 8_000;

/** Reserved height per supported banner size, so an arriving ad cannot shift. */
export const EXOCLICK_RESERVED_HEIGHTS = Object.freeze({
  "300x250": 250,
  "728x90": 90,
  responsive: 250,
} as const);

/**
 * The only surfaces a banner may appear on. These are the same browsing pages
 * the existing banner architecture already approves — never a lobby below its
 * own URL, never a match, a board, a live queue or the post-match overlay.
 */
export const EXOCLICK_PLACEMENTS = ["home", "hub", "leaderboard", "profile"] as const;

export type ExoclickPlacement = (typeof EXOCLICK_PLACEMENTS)[number];

export type ExoclickBannerSize = keyof typeof EXOCLICK_RESERVED_HEIGHTS;

export function isExoclickPlacement(value: unknown): value is ExoclickPlacement {
  return (
    typeof value === "string" &&
    (EXOCLICK_PLACEMENTS as readonly string[]).includes(value)
  );
}

/**
 * The ONE route each placement belongs to — exact matching, exactly like the
 * existing banner integration. A lobby, match, board or alias is absent from
 * every list, so mounting this anywhere else injects nothing.
 */
export const EXOCLICK_PLACEMENT_ROUTES: Readonly<
  Record<ExoclickPlacement, readonly string[]>
> = Object.freeze({
  home: ["/"],
  hub: ["/games", "/casino"],
  leaderboard: ["/classement"],
  profile: ["/profil"],
});

/** True when `pathname` is exactly the route this placement may serve. */
export function exoclickRouteMatchesPlacement(
  pathname: string | null | undefined,
  placement: unknown,
): boolean {
  if (!isExoclickPlacement(placement)) return false;
  if (typeof pathname !== "string") return false;

  const path = pathname.split(/[?#]/)[0];
  const normalized = path.length > 1 ? path.replace(/\/+$/, "") : path;
  return EXOCLICK_PLACEMENT_ROUTES[placement].includes(normalized);
}

/** The container id for a placement (one banner per page). */
export function exoclickContainerId(placement: ExoclickPlacement): string {
  return `${EXOCLICK_CONTAINER_PREFIX}-${placement}`;
}

/** Opt-in switch: only an explicit "true" / "1" turns anything ON. */
function switchOn(value: string | undefined): boolean {
  const raw = (value ?? "").trim().toLowerCase();
  return raw === "true" || raw === "1";
}

/** Build-time switch (`NEXT_PUBLIC_EXOCLICK_ENABLED`). Off unless opted in. */
export function exoclickBannerEnabled(): boolean {
  return switchOn(process.env.NEXT_PUBLIC_EXOCLICK_ENABLED);
}

/** Runtime switch (`EXOCLICK_ENABLED`), read per request on the server. */
export function exoclickBannerEnabledOnServer(): boolean {
  return switchOn(process.env.EXOCLICK_ENABLED);
}

/**
 * Consent is required by default. The client unit only injects the tag when
 * the visitor's stored consent record says "accepted"; a deploy that does not
 * need that basis can opt out explicitly.
 */
export function exoclickRequiresConsent(): boolean {
  return (
    (process.env.NEXT_PUBLIC_EXOCLICK_REQUIRES_CONSENT ?? "").trim().toLowerCase() !==
    "false"
  );
}

/** True only for an explicit "accepted" record; undecided and declined fail closed. */
export function exoclickConsentSatisfied(
  consent: "accepted" | "declined" | null | undefined,
): boolean {
  return consent === "accepted";
}

/** True when `hostname` is exoclick.com/magsrv.com or one of their subdomains. */
export function isExoclickProviderHost(hostname: string | null | undefined): boolean {
  const host = (hostname ?? "").trim().toLowerCase();
  if (!host) return false;
  return EXOCLICK_PROVIDER_HOSTS.some(
    (domain) => host === domain || host.endsWith(`.${domain}`),
  );
}

/**
 * Validate a provider loader URL. Protocol-relative (`//host/path`) is what the
 * dashboard may hand out and is accepted (rewritten to https); absolute https
 * is passed through unchanged. Everything else — another host, `http:`,
 * credentials, an unparsable or absurd value — resolves to null so the banner
 * renders NOTHING instead of loading a tag we cannot vouch for.
 */
export function normalizeExoclickScriptUrl(
  value: string | null | undefined,
): string | null {
  const raw = (value ?? "").trim();
  if (!raw || raw.length > 2_048) return null;

  const absolute = raw.startsWith("//") ? `https:${raw}` : raw;

  let parsed: URL;
  try {
    parsed = new URL(absolute);
  } catch {
    return null;
  }

  if (parsed.protocol !== "https:") return null;
  if (!isExoclickProviderHost(parsed.hostname)) return null;
  if (parsed.username || parsed.password) return null;

  return parsed.toString();
}

/** The loader URL this deploy will use, or null when the override is invalid. */
export function exoclickBannerScriptUrl(): string | null {
  const override = (process.env.NEXT_PUBLIC_EXOCLICK_SCRIPT_URL ?? "").trim();
  if (!override) return normalizeExoclickScriptUrl(EXOCLICK_AD_PROVIDER_URL);
  return normalizeExoclickScriptUrl(override);
}

// Static `process.env.NEXT_PUBLIC_*` reads only: Next inlines these at build
// time. A dynamic `process.env[name]` would be undefined in the browser.

function rawZoneValue(placement: ExoclickPlacement): string | undefined {
  switch (placement) {
    case "home":
      return process.env.NEXT_PUBLIC_EXOCLICK_ZONE_HOME;
    case "hub":
      return process.env.NEXT_PUBLIC_EXOCLICK_ZONE_HUB;
    case "leaderboard":
      return process.env.NEXT_PUBLIC_EXOCLICK_ZONE_LEADERBOARD;
    case "profile":
      return process.env.NEXT_PUBLIC_EXOCLICK_ZONE_PROFILE;
    default:
      return undefined;
  }
}

/**
 * The zone id for a placement, or null. Numeric only — a dashboard zone id is
 * never invented, and a placeholder cannot be shoehorned in here.
 */
export function exoclickZoneId(placement: unknown): string | null {
  if (!isExoclickPlacement(placement)) return null;
  const trimmed = (rawZoneValue(placement) ?? "").trim();
  return /^\d{1,20}$/.test(trimmed) ? trimmed : null;
}

function rawInsClassValue(placement: ExoclickPlacement): string | undefined {
  switch (placement) {
    case "home":
      return process.env.NEXT_PUBLIC_EXOCLICK_INS_CLASS_HOME;
    case "hub":
      return process.env.NEXT_PUBLIC_EXOCLICK_INS_CLASS_HUB;
    case "leaderboard":
      return process.env.NEXT_PUBLIC_EXOCLICK_INS_CLASS_LEADERBOARD;
    case "profile":
      return process.env.NEXT_PUBLIC_EXOCLICK_INS_CLASS_PROFILE;
    default:
      return undefined;
  }
}

/**
 * The provider-generated `<ins>` class token for a placement, or null.
 *
 * This is the one part of the tag that is genuinely per-account: it must be
 * copied from the same zone the id comes from. There is no default.
 */
export function exoclickInsClass(placement: unknown): string | null {
  if (!isExoclickPlacement(placement)) return null;
  const raw =
    (rawInsClassValue(placement) ?? "").trim() ||
    (process.env.NEXT_PUBLIC_EXOCLICK_INS_CLASS ?? "").trim();
  return /^[A-Za-z][A-Za-z0-9_-]{2,63}$/.test(raw) ? raw : null;
}

function rawSizeValue(placement: ExoclickPlacement): string | undefined {
  switch (placement) {
    case "home":
      return process.env.NEXT_PUBLIC_EXOCLICK_BANNER_SIZE_HOME;
    case "hub":
      return process.env.NEXT_PUBLIC_EXOCLICK_BANNER_SIZE_HUB;
    case "leaderboard":
      return process.env.NEXT_PUBLIC_EXOCLICK_BANNER_SIZE_LEADERBOARD;
    case "profile":
      return process.env.NEXT_PUBLIC_EXOCLICK_BANNER_SIZE_PROFILE;
    default:
      return undefined;
  }
}

const BANNER_SIZES: readonly ExoclickBannerSize[] = [
  "300x250",
  "728x90",
  "responsive",
];

/** The container size this placement reserves. Defaults to 300x250. */
export function exoclickBannerSize(placement: unknown): ExoclickBannerSize {
  if (!isExoclickPlacement(placement)) return "300x250";
  const raw = (
    (rawSizeValue(placement) ?? "").trim() ||
    (process.env.NEXT_PUBLIC_EXOCLICK_BANNER_SIZE ?? "").trim()
  ).toLowerCase();
  return (BANNER_SIZES as readonly string[]).includes(raw)
    ? (raw as ExoclickBannerSize)
    : "300x250";
}

/** Reserved height for a placement, so an arriving creative cannot shift the page. */
export function exoclickReservedHeight(placement: unknown): number {
  return EXOCLICK_RESERVED_HEIGHTS[exoclickBannerSize(placement)];
}

/** Container width cap: a 300x250 banner is centred in a 300 px column. */
export function exoclickContainerMaxWidth(placement: unknown): number {
  return exoclickBannerSize(placement) === "300x250" ? 300 : 728;
}

/**
 * True only when the placement is approved AND every provider value exists:
 * a valid loader URL, a real zone id and the provider-generated class token.
 */
export function exoclickBannerConfigured(placement: unknown): boolean {
  return (
    isExoclickPlacement(placement) &&
    exoclickBannerScriptUrl() !== null &&
    exoclickZoneId(placement) !== null &&
    exoclickInsClass(placement) !== null
  );
}

/** The cheap, server-side gates: switched on, configured, approved placement. */
export function exoclickBannerAllowed({
  enabled,
  configured,
  placement,
}: {
  enabled: boolean;
  configured: boolean;
  placement: unknown;
}): boolean {
  return enabled && configured && isExoclickPlacement(placement);
}

/** The final gate: the SERVER's ad-free answer, never a client flag. */
export function exoclickBannerVisibleToViewer({
  allowed,
  adFree,
}: {
  allowed: boolean;
  adFree: boolean;
}): boolean {
  return allowed && !adFree;
}

/**
 * True when the provider loader still has to be added to the document.
 *
 * One loader per document: a remount reuses the existing element, and a
 * client-side navigation that keeps the document reuses it too. A changed
 * configuration does not stack a second loader.
 */
export function shouldInjectExoclickScript(
  existingScriptUrl: string | null,
  desiredUrl: string | null,
): boolean {
  return desiredUrl !== null && existingScriptUrl === null;
}
