// src/lib/learnCurriculumTranslations.js
//
// Course, lesson, step, hint and completion copy for the full Solitaire
// curriculum. Kept separate from the Learn interface copy so the catalog can be
// read as a curriculum, while `learnTranslations.js` still exposes one merged
// `learn` namespace to the components.
//
// Each step tuple is:
//   [stepId, instruction, explanation, incorrect, hint1, hint2]

function buildCatalog({ courses, lessons }) {
  return {
    courses: Object.fromEntries(
      Object.entries(courses).map(([id, [title, description]]) => [
        id,
        { title, description },
      ]),
    ),
    lessons: Object.fromEntries(
      lessons.map(([id, title, description, success, steps]) => [
        id,
        {
          title,
          description,
          success,
          step: Object.fromEntries(
            steps.map(
              ([stepId, instruction, explanation, incorrect, hint1, hint2]) => [
                stepId,
                { instruction, explanation, incorrect, hint1, hint2 },
              ],
            ),
          ),
        },
      ]),
    ),
  };
}

