type ClassificationInput = {
  kind: string;
  tags: AnalysisEventTag[];
  delta: number;
  regret: number;
  gap: number;
  uniqueBest: boolean;
  tiedBest: boolean;
  onlyLegal: boolean;
  usedDeep: boolean;
  deepPlayedIsBest: boolean;
  deepGap: number;
};

type Classification = { rating: MoveRating; reasonCodes: AnalysisReasonCode[] };

/**
 * Turn measured facts into a rating and compact reason codes.
 *
 * Order is deliberate: no-decision → draw → provable regret → positive value.
 * A draw is never rated: cycling the stock is how the game is played, and
 * calling it good or bad would be noise (the redeal case is still TAGGED).
 */
function classifyMove(input: ClassificationInput): Classification {
  const {
    kind,
    tags,
    delta,
    regret,
    gap,
    uniqueBest,
    tiedBest,
    onlyLegal,
    usedDeep,
    deepPlayedIsBest,
    deepGap,
  } = input;

  const deepReason: AnalysisReasonCode[] = usedDeep ? ["deep-search"] : [];

  // A forced move is not a decision, however much progress it makes.
  if (onlyLegal) {
    return { rating: "normal", reasonCodes: ["only-legal-move", ...deepReason] };
  }

  // Draws are information cycling, never a quality signal on their own.
  if (kind === "draw") {
    if (tags.includes("wasted-redeal") && regret >= INACCURACY_REGRET) {
      return {
        rating: "inaccuracy",
        reasonCodes: ["not-best", "reversible-waste", ...deepReason],
      };
    }
    return { rating: "normal", reasonCodes: ["routine", "draw-cycled", ...deepReason] };
  }

  // ── Provable regret ────────────────────────────────────────────────────
  // Only reachable when a legal, visible alternative scored strictly better.
  // A no-op shuffle and a foundation pull are capped at `mistake`: both can be
  // the least-bad option in a constrained board, so they never earn a blunder.
  const cappedAtMistake =
    tags.includes("pointless-shuffle") || tags.includes("pulled-from-foundation");
  let severity = 0;
  if (regret >= BLUNDER_REGRET) severity = 3;
  else if (regret >= MISTAKE_REGRET) severity = 2;
  else if (regret >= INACCURACY_REGRET) severity = 1;
  if (cappedAtMistake) severity = Math.min(severity, 2);

  if (severity > 0) {
    const rating: MoveRating =
      severity === 3 ? "blunder" : severity === 2 ? "mistake" : "inaccuracy";
    return {
      rating,
      reasonCodes: [
        "not-best",
        "better-alternative",
        ...(cappedAtMistake ? (["reversible-waste"] as AnalysisReasonCode[]) : []),
        ...deepReason,
      ],
    };
  }

  // ── Positive value ─────────────────────────────────────────────────────
  const structural =
    tags.includes("opened-column") ||
    tags.includes("foundation-cascade") ||
    tags.includes("unlocked-sequence");

  if (uniqueBest) {
    // Brilliant requires a verifiable unlock, not merely a good move: opening a
    // column AND making a King-led run usable in it, in the same move.
    if (
      tags.includes("opened-column") &&
      tags.includes("unlocked-sequence") &&
      delta >= 2 * GREAT_DELTA
    ) {
      return {
        rating: "brilliant",
        reasonCodes: ["best-available", "structural-unlock", ...deepReason],
      };
    }

    if (
      delta >= GREAT_DELTA &&
      (structural ||
        gap >= GREAT_GAP ||
        (usedDeep && deepPlayedIsBest && deepGap >= DEEP_GREAT_GAP))
    ) {
      return {
        rating: "great",
        reasonCodes: [
          "best-available",
          structural ? "structural-unlock" : "meaningful-gain",
          ...deepReason,
        ],
      };
    }

    // A clearly-best reveal (a big gap to every alternative) is a meaningful
    // decision even though a single card is worth less than a foundation card.
    if (tags.includes("revealed-hidden") && gap >= 300 && delta >= GOOD_DELTA) {
      return {
        rating: "great",
        reasonCodes: ["best-available", "structural-unlock", ...deepReason],
      };
    }

    if (delta >= GOOD_DELTA) {
      return {
        rating: "good",
        reasonCodes: ["best-available", "meaningful-gain", ...deepReason],
      };
    }
  }

  if (tiedBest && delta >= GOOD_DELTA) {
    return {
      rating: "good",
      reasonCodes: ["tied-best", "meaningful-gain", ...deepReason],
    };
  }

  return {
    rating: "normal",
    reasonCodes: [tiedBest ? "tied-best" : "no-material-gain", ...deepReason],
  };
}

