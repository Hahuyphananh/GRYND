function emptyRatingCounts(): Record<MoveRating, number> {
  const counts = {} as Record<MoveRating, number>;
  for (const key of RATING_KEYS) counts[key] = 0;
  return counts;
}

function emptySummary(): GameAnalysisSummary {
  return {
    movesAnalyzed: 0,
    ratings: emptyRatingCounts(),
    accuracy: null,
    totalRegret: 0,
    averageRegret: 0,
    deepSearchMoves: 0,
    informationFair: true,
  };
}

function emptyResult(version: number, rejectedAt: number | null): GameAnalysis {
  return {
    version,
    reconstructable: false,
    complete: false,
    rejectedAt,
    perMove: [],
    moments: [],
    summary: emptySummary(),
  };
}

function positiveInt(value: unknown, fallback: number): number {
  const number = Number(value);
  return Number.isFinite(number) && number > 0 ? Math.floor(number) : fallback;
}

/**
 * Analyse one game.
 *
 * @param deal   the canonical deal the game was played from (server-side or a
 *               Solo/Daily seed rebuilt by the caller).
 * @param moves  the accepted move log, in order, shaped like
 *               `solitaire_duel_moves` rows: `{ kind, move }`. Replaying starts
 *               from `initialStateFromDeal(deal)`.
 * @param options optional budgets; all have safe defaults.
 *
 * The function never throws on a bad log: it stops at the first entry the
 * authoritative engine refuses, marks the game not reconstructable, and still
 * returns the analysis of every move played before it. An interrupted or
 * undo-truncated log is therefore a normal, reported outcome rather than an
 * error.
 */
export function analyzeSolitaireGame({
  deal,
  moves,
  options = {},
}: {
  deal: SolitaireDeal;
  moves: readonly AnalysisLogEntry[];
  options?: AnalysisOptions;
}): GameAnalysis {
  if (!deal || !Array.isArray(deal.tableau) || !Array.isArray(moves)) {
    return emptyResult(ANALYSIS_VERSION, 0);
  }

  const memo = new Map<string, number>();
  const perMove: MoveAnalysis[] = [];
  const ratingCounts = emptyRatingCounts();
  let state = initialStateFromDeal(deal);
  let rejectedAt: number | null = null;
  let totalRegret = 0;
  let deepSearchMoves = 0;

  const deepEnabled = options.deepSearch !== false;
  const deepBudget = {
    nodes: 0,
    max: positiveInt(options.deepNodeBudget, DEEP_DEFAULT_NODE_BUDGET),
  };
  const deepBeam = positiveInt(options.deepBeamWidth, DEEP_DEFAULT_BEAM);
  const deepDepth = positiveInt(options.deepMaxDepth, DEEP_DEFAULT_DEPTH);
  const deepMoveCap =
    options.deepMaxMoves !== undefined && options.deepMaxMoves !== null
      ? Math.max(0, Math.floor(Number(options.deepMaxMoves)) || 0)
      : DEEP_MAX_MOVES_DEFAULT;
  const maxMoments = positiveInt(options.maxMoments, DEFAULT_MAX_MOMENTS);

  for (let index = 0; index < moves.length; index += 1) {
    const entry = moves[index];
    const raw = entry && typeof entry === "object" ? entry.move : undefined;
    const normalized = normalizeMove(raw);
    if (!("move" in normalized)) {
      rejectedAt = index;
      break;
    }
    if (typeof entry?.kind === "string" && entry.kind !== normalized.move.kind) {
      rejectedAt = index;
      break;
    }

    const move = normalized.move;
    const applied = applyMove({ state, move });
    if (!applied.ok) {
      rejectedAt = index;
      break;
    }
    const after = applied.state as SolitaireState;
    const revealed = (applied as { revealed?: Card[] }).revealed ?? [];

    const scoreBefore = scoreWithMemo(state, memo);
    const scoreAfter = scoreWithMemo(after, memo);
    const delta = scoreAfter - scoreBefore;

    // Every candidate the player could actually choose from, scored on the
    // resulting VISIBLE position. `legalMoves` is the engine's own list.
    const candidates: AppliedScore[] = [];
    for (const candidate of legalMoves(state)) {
      const scored = applyAndScore(state, candidate, memo);
      if (scored) candidates.push(scored);
    }
    const playedKey = moveKey(move);
    if (!candidates.some((candidate) => candidate.key === playedKey)) {
      // Defensive: a legal applied move should always be in the list, but the
      // played move's own score is authoritative if it somehow is not.
      candidates.push({ move, key: playedKey, score: scoreAfter });
    }

    const onlyLegal = candidates.length <= 1;
    const scores = candidates.map((candidate) => candidate.score);
    const bestScore = scores.length > 0 ? Math.max(...scores) : scoreAfter;
    const playedCandidate = candidates.find((candidate) => candidate.key === playedKey);
    const playedScore = playedCandidate ? playedCandidate.score : scoreAfter;
    const bestCandidates = candidates.filter((candidate) => candidate.score === bestScore);
    const uniqueBest = playedScore >= bestScore && bestCandidates.length === 1;
    const tiedBest = playedScore >= bestScore && bestCandidates.length > 1;
    const regret = Math.max(0, bestScore - playedScore);
    const belowBest = scores.filter((score) => score < bestScore);
    const secondBest = belowBest.length > 0 ? Math.max(...belowBest) : bestScore;
    const gap = bestScore - secondBest;

    const tags: AnalysisEventTag[] = [];

    // ── Draw events (before-state decides draw vs redeal) ────────────────
    if (move.kind === "draw") {
      const stockBefore = state.stock?.length ?? 0;
      const wasteBefore = state.waste?.length ?? 0;
      if (stockBefore > 0) {
        tags.push("stock-draw");
      } else if (wasteBefore > 0) {
        tags.push("waste-redeal");
        if (candidates.some((candidate) => candidate.key !== "draw")) {
          tags.push("wasted-redeal");
        }
      }
    }

    // ── Reveal / structure ──────────────────────────────────────────────
    if (revealed.length > 0) tags.push("revealed-hidden");
    if (leavesColumnEmpty(state, after, move)) tags.push("opened-column");
    if (move.kind === "tableau-to-tableau" && move.card.rank === KING) {
      const target = state.tableau?.[move.toColumn] ?? [];
      if (target.length === 0) tags.push("king-to-empty-column");
    }
    if (move.kind === "tableau-to-foundation" || move.kind === "waste-to-foundation") {
      tags.push("foundation-progress");
    }
    if (move.kind === "foundation-to-tableau") tags.push("pulled-from-foundation");
    if (
      move.kind === "tableau-to-tableau" &&
      revealed.length === 0 &&
      !tags.includes("opened-column") &&
      delta <= 0
    ) {
      tags.push("pointless-shuffle");
    }

    // ── Identity-dependent structure is only fair when nothing was flipped ─
    // If this move turned over a hidden card, any opportunity it creates may
    // depend on WHICH card that was. Nobody knew it, so we do not credit it.
    if (revealed.length === 0) {
      const opportunitiesBefore = foundationOpportunities(state);
      const opportunitiesAfter = foundationOpportunities(after);
      if (opportunitiesAfter >= opportunitiesBefore + 2) {
        tags.push("foundation-cascade");
      }
      if (!hasKingPlacement(state) && hasKingPlacement(after)) {
        tags.push("unlocked-sequence");
      }
    }

    // ── Budgeted deeper comparison on ambiguous decisions only ───────────
    // `gap` is Infinity for a single scored candidate; `onlyLegal` already
    // short-circuits those, so this branch always has a real comparison.
    const ambiguous = uniqueBest ? gap <= GREAT_GAP : regret <= GREAT_GAP;
    let usedDeep = false;
    let deepPlayedIsBest = false;
    let deepGap = 0;

    if (
      deepEnabled &&
      !onlyLegal &&
      candidates.length >= 3 &&
      ambiguous &&
      deepSearchMoves < deepMoveCap &&
      deepBudget.nodes < deepBudget.max
    ) {
      const pool = candidates
        .slice()
        .sort((a, b) => b.score - a.score || a.key.localeCompare(b.key))
        .slice(0, Math.max(2, deepBeam));
      if (!pool.some((candidate) => candidate.key === playedKey) && playedCandidate) {
        pool.push(playedCandidate);
      }
      if (pool.length >= 2) {
        const deep = pool
          .map((candidate) => ({
            key: candidate.key,
            score: deepScore(state, candidate.move, deepDepth, deepBudget, memo, deepBeam),
          }))
          .filter((row): row is { key: string; score: number } => row.score !== null);

        if (deep.length >= 2) {
          usedDeep = true;
          deepSearchMoves += 1;
          const deepBest = Math.max(...deep.map((row) => row.score));
          const playedDeep = deep.find((row) => row.key === playedKey);
          const deepWinners = deep.filter((row) => row.score === deepBest);
          deepPlayedIsBest =
            Boolean(playedDeep) && playedDeep!.score >= deepBest && deepWinners.length === 1;
          const deepBelow = deep.map((row) => row.score).filter((score) => score < deepBest);
          deepGap = deepBelow.length > 0 ? deepBest - Math.max(...deepBelow) : 0;
        }
      }
    }

    const { rating, reasonCodes } = classifyMove({
      kind: move.kind,
      tags,
      delta,
      regret,
      gap,
      uniqueBest,
      tiedBest,
      onlyLegal,
      usedDeep,
      deepPlayedIsBest,
      deepGap,
    });

    perMove.push({
      ply: index,
      kind: move.kind,
      rating,
      tags,
      scoreBefore,
      scoreAfter,
      delta,
      regret,
      commentaryEligible:
        rating === "great" ||
        rating === "brilliant" ||
        rating === "mistake" ||
        rating === "blunder",
      reasonCodes,
    });
    ratingCounts[rating] += 1;
    totalRegret += regret;

    state = after;
  }

  const movesAnalyzed = perMove.length;
  const reconstructable = rejectedAt === null;

  // Important moments: real decisions and meaningful events, strongest first,
  // then presented in play order. Capped so the strip stays readable.
  const moments: AnalysisMoment[] = perMove
    .filter(
      (move) => SIGNIFICANCE[move.rating] >= 2 || move.tags.some((tag) => MOMENT_TAGS.has(tag))
    )
    .map((move) => ({
      ply: move.ply,
      rating: move.rating,
      tags: move.tags,
      reasonCodes: move.reasonCodes,
      _significance:
        SIGNIFICANCE[move.rating] * 10 +
        (move.tags.includes("unlocked-sequence") ? 3 : 0) +
        (move.tags.includes("opened-column") ? 2 : 0),
    }))
    .sort((a, b) => b._significance - a._significance || a.ply - b.ply)
    .slice(0, maxMoments)
    .sort((a, b) => a.ply - b.ply)
    .map(({ _significance, ...moment }) => moment);

  const averageRegret = movesAnalyzed > 0 ? totalRegret / movesAnalyzed : 0;

  return {
    version: ANALYSIS_VERSION,
    reconstructable,
    complete: Boolean(state.completed),
    rejectedAt,
    perMove,
    moments,
    summary: {
      movesAnalyzed,
      ratings: ratingCounts,
      accuracy:
        movesAnalyzed > 0
          ? Math.max(
              0,
              Math.min(100, Math.round((100 - (averageRegret / FOUNDATION_VALUE) * 100) * 10) / 10)
            )
          : null,
      totalRegret,
      averageRegret: Math.round(averageRegret * 10) / 10,
      deepSearchMoves,
      informationFair: true,
    },
  };
}
