// src/lib/solitaire-duel/analysis.ts
//
// THE GAME REVIEW ENGINE — deterministic, pure, and information-fair.
//
// It replays a game's own move log through the authoritative engine (`rules.ts`)
// and rates each accepted move against the moves that were available FROM THE
// BOARD THE PLAYER COULD SEE at that moment. There is no LLM, no external API,
// no randomness, no clock and no I/O: the same `{deal, moves}` always produces
// byte-identical output, which is what lets this run in a Web Worker later and
// lets a server reproduce any stored analysis without trusting it.
//
// ── WHAT THIS MODULE IS NOT ────────────────────────────────────────────────
//
//   * It is NOT a second game engine. Legality, application, progress and
//     completion all come from `rules.ts`; the candidate move list comes from
//     `legalMoves` in `ai.ts`. Nothing here re-implements Klondike.
//   * It is NOT a solver. Klondike's state space is far too large to search
//     exhaustively per move, and a review that takes minutes is useless. The
//     rating is a one-ply comparison by default, with a small, strictly
//     budgeted lookahead used only on genuinely ambiguous decisions.
//   * It is NOT authoritative. Ratings are commentary metadata. They never
//     touch the match row, Elo, trophies, rewards, leaderboards or completion.
//
// ── INFORMATION FAIRNESS (the load-bearing rule) ───────────────────────────
//
// The analyser is handed the SERVER's board, which knows every face-down card
// and the stock order. A player did not. Two construction choices make that
// irrelevant rather than merely discouraged:
//
//   1. `evaluateSolitairePosition` reads ONLY count/structural features:
//      foundation depth, how many tableau cards have been turned over, empty
//      columns, and how deeply face-down cards are buried. It never reads a
//      face-down card's identity, and never reads the stock's contents or order.
//   2. Every candidate is generated by the engine's own `legalMoves`, which
//      only ever addresses face-up cards and the waste top. A hidden card is
//      simply not addressable.
//
// Structural tags that WOULD peer past the current information horizon (a
// foundation cascade or a newly usable empty column) are suppressed on a move
// that turns over a hidden card, because those opportunities depend on which
// card was behind it — which nobody knew when choosing. That suppression is why
// a brilliant rating can never be earned with hindsight.
//
// Negative ratings follow the same rule strictly: a move is only called an
// inaccuracy/mistake/blunder when a BETTER LEGAL MOVE WAS VISIBLE at that
// placement. If the engine cannot establish that, the move is `normal` or
// `good`.

