/** Chess.com-style classification. `normal` is the default for routine play. */
export type MoveRating =
  "normal" | "good" | "great" | "brilliant" | "inaccuracy" | "mistake" | "blunder";

/** A reliably-determinable event, derived from engine state only. */
export type AnalysisEventTag =
  /** A draw with cards left in the stock (routine, never rated good/bad). */
  | "stock-draw"
  /** A draw that recycled the waste because the stock was empty. */
  | "waste-redeal"
  /** The move turned a face-down tableau card face-up. */
  | "revealed-hidden"
  /** The move left its source tableau column empty. */
  | "opened-column"
  /** A King (with a run) can now use an empty column that was not usable before. */
  | "unlocked-sequence"
  /** Two or more immediate foundation opportunities were created at once. */
  | "foundation-cascade"
  /** A redeal was played while a productive move was on the table. */
  | "wasted-redeal"
  /** A tableau shuffle that revealed nothing, freed nothing and gained nothing. */
  | "pointless-shuffle"
  /** A card was taken back off a foundation. */
  | "pulled-from-foundation"
  /** The move put a King into an empty column. */
  | "king-to-empty-column"
  /** The move put a card on a foundation. */
  | "foundation-progress";

/** Compact, UI-friendly explanation codes. Never prose. */
export type AnalysisReasonCode =
  | "best-available"
  | "tied-best"
  | "not-best"
  | "better-alternative"
  | "meaningful-gain"
  | "structural-unlock"
  | "routine"
  | "draw-cycled"
  | "reversible-waste"
  | "only-legal-move"
  | "no-material-gain"
  | "deep-search";

/** One accepted move's analysis. Small, flat and JSON-safe. */
export type MoveAnalysis = {
  /** 0-based index in the move log (the store's `ply` for a seat). */
  ply: number;
  /** The engine's move kind, for timeline labels. */
  kind: string;
  rating: MoveRating;
  tags: AnalysisEventTag[];
  /** Position value before the move, on the internal scale. */
  scoreBefore: number;
  /** Position value after the move, on the internal scale. */
  scoreAfter: number;
  /** `scoreAfter - scoreBefore`. Never negative for a hidden-information reason. */
  delta: number;
  /** How much value the best VISIBLE alternative would have added instead. */
  regret: number;
  /** True only for ratings worth a coach's line (great/brilliant/mistake/blunder). */
  commentaryEligible: boolean;
  reasonCodes: AnalysisReasonCode[];
};

/** A non-routine move, for a "key moments" strip. */
export type AnalysisMoment = {
  ply: number;
  rating: MoveRating;
  tags: AnalysisEventTag[];
  reasonCodes: AnalysisReasonCode[];
};

export type GameAnalysisSummary = {
  movesAnalyzed: number;
  ratings: Record<MoveRating, number>;
  /** 0–100, one decimal, derived from average regret; `null` for an empty log. */
  accuracy: number | null;
  totalRegret: number;
  averageRegret: number;
  /** How many moves used the budgeted deeper comparison. */
  deepSearchMoves: number;
  /** Always true: the evaluator reads no hidden information (see header). */
  informationFair: true;
};

export type GameAnalysis = {
  version: number;
  /** Every submitted move was legal and replayed exactly. */
  reconstructable: boolean;
  /** The replayed board reached all 52 cards on the foundations. */
  complete: boolean;
  /** Index of the first illegal/mismatched log entry, or null. */
  rejectedAt: number | null;
  perMove: MoveAnalysis[];
  moments: AnalysisMoment[];
  summary: GameAnalysisSummary;
};

export type AnalysisOptions = {
  /** Enable the budgeted deeper comparison (default true). */
  deepSearch?: boolean;
  /** Total nodes the deeper comparison may expand for the WHOLE game. */
  deepNodeBudget?: number;
  /** Children kept per node in the deeper comparison. */
  deepBeamWidth?: number;
  /** Plies beyond the played move the deeper comparison may look. */
  deepMaxDepth?: number;
  /** Hard cap on how many moves may use the deeper comparison. */
  deepMaxMoves?: number;
  /** Maximum key moments returned (default 12). */
  maxMoments?: number;
};

/** A stored log entry, exactly as `solitaire_duel_moves` rows are shaped. */
export type AnalysisLogEntry = { kind?: unknown; move?: unknown };

// ──────────────────────────────────────────────────────────────────────────
// Scoring constants — one scale, documented
// ──────────────────────────────────────────────────────────────────────────

/** One foundation card is the unit of progress. Regret thresholds use it too. */
const FOUNDATION_VALUE = 1_000;
/** A newly turned-over tableau card is worth this much information progress. */
const REVEAL_VALUE = 150;
/** An empty tableau column is a reusable structural resource. */
const EMPTY_COLUMN_VALUE = 120;
/** Per depth unit of a still-face-down card: buried cards are future work. */
const BURIED_VALUE = 18;

/** Positive thresholds, in the same units. */
const GOOD_DELTA = 150;
const GREAT_DELTA = 400;
const GREAT_GAP = 250;
const DEEP_GREAT_GAP = 300;

/** Negative thresholds. A move must beat one of these to be criticised. */
const INACCURACY_REGRET = 250;
const MISTAKE_REGRET = 600;
const BLUNDER_REGRET = 1_100;

/** Deeper-comparison defaults, deliberately tiny. */
const DEEP_DEFAULT_NODE_BUDGET = 4_000;
const DEEP_DEFAULT_BEAM = 4;
const DEEP_DEFAULT_DEPTH = 2;
/**
 * A FIXED cap, deliberately not a share of the log length.
 *
 * Tying it to `moves.length` would make a game's first six moves analyse
 * differently when the log is truncated (an abandoned game, an undo), which is
 * exactly the case a review screen sees. A fixed cap keeps the analysis of any
 * prefix identical to the prefix of the full game, while the shared node budget
 * is what actually bounds the work.
 */
const DEEP_MAX_MOVES_DEFAULT = 16;
/** A lookahead gain is discounted: it is a chance, not a realised position. */
const DEEP_PLANNING_WEIGHT = 0.3;

const MEMO_LIMIT = 4_000;
const DEFAULT_MAX_MOMENTS = 12;

const RATING_KEYS: readonly MoveRating[] = Object.freeze([
  "normal",
  "good",
  "great",
  "brilliant",
  "inaccuracy",
  "mistake",
  "blunder",
]);

/** Tags that make a non-routine move a "moment" even when its rating is normal. */
const MOMENT_TAGS: ReadonlySet<AnalysisEventTag> = new Set([
  "opened-column",
  "unlocked-sequence",
  "foundation-cascade",
  "wasted-redeal",
  "king-to-empty-column",
]);

const SIGNIFICANCE: Record<MoveRating, number> = {
  normal: 0,
  good: 1,
  great: 4,
  brilliant: 5,
  inaccuracy: 1,
  mistake: 2,
  blunder: 3,
};

// ──────────────────────────────────────────────────────────────────────────
// Position evaluation — counts and structure only
// ──────────────────────────────────────────────────────────────────────────

function emptyColumnCount(state: SolitaireState): number {
  let empty = 0;
  for (const column of state.tableau ?? []) {
    if (!column || column.length === 0) empty += 1;
  }
  return empty;
}

/**
 * How deeply face-down cards are buried, summed over the board.
 *
 * A face-down position at index `i` of a column of length `n` has `n - i` cards
 * above it (itself included), so a card at the bottom of a long column is worth
 * more future work than one about to be exposed. Purely positional: no identity
 * and no stock order is read.
 */
function buriedPenalty(state: SolitaireState): number {
  let total = 0;
  for (const column of state.tableau ?? []) {
    for (let index = 0; index < column.length; index += 1) {
      if (!column[index]?.faceUp) total += column.length - index;
    }
  }
  return total * BURIED_VALUE;
}

/**
 * The visible position's value, on the engine-wide scale.
 *
 * Reads: foundation depth, how many tableau cards have been turned over
 * (`revealedTableauCount` — the engine's own monotone information metric), the
 * number of empty columns, and buried-card depth. It deliberately reads NO
 * card identity of a hidden card and NOTHING from the stock except how many
 * cards remain.
 *
 * Exported for tests and for future verification: a server can recompute any
 * position score with the same function.
 */
export function evaluateSolitairePosition(state: SolitaireState): number {
  if (!state || !Array.isArray(state.tableau)) return 0;
  const foundations = foundationCount(state);
  const revealed = revealedTableauCount(state);
  const empty = emptyColumnCount(state);
  const buried = buriedPenalty(state);
  return (
    foundations * FOUNDATION_VALUE + revealed * REVEAL_VALUE + empty * EMPTY_COLUMN_VALUE - buried
  );
}

// ──────────────────────────────────────────────────────────────────────────
// Visible-state memoisation
// ──────────────────────────────────────────────────────────────────────────

/**
 * A digest of everything the evaluator may read.
 *
 * Face-down cards contribute a single `h` marker (their identity is absent),
 * the stock contributes only its length, and the waste is included because it
 * is fully visible. Two boards that differ only in hidden information share a
 * digest, so they can never be scored differently from the cache either.
 */
function visibleDigest(state: SolitaireState): string {
  const tableau = (state.tableau ?? [])
    .map((column) =>
      column
        .map((pile) => (pile.faceUp && pile.card ? `${pile.card.suit[0]}${pile.card.rank}` : "h"))
        .join(",")
    )
    .join("|");
  const foundations = SUITS.map((suit) =>
    (state.foundations?.[suit] ?? []).map((card) => `${card.suit[0]}${card.rank}`).join(",")
  ).join("|");
  const waste = (state.waste ?? []).map((card) => `${card.suit[0]}${card.rank}`).join(",");
  return `${tableau}#${foundations}#${waste}#${state.stock?.length ?? 0}`;
}

function scoreWithMemo(state: SolitaireState, memo: Map<string, number>): number {
  const key = visibleDigest(state);
  const cached = memo.get(key);
  if (cached !== undefined) return cached;
  const score = evaluateSolitairePosition(state);
  if (memo.size >= MEMO_LIMIT) memo.clear();
  memo.set(key, score);
  return score;
}

// ──────────────────────────────────────────────────────────────────────────
// Structural probes (all visible-information only)
// ──────────────────────────────────────────────────────────────────────────

/** Immediate foundation moves available right now (penthouse tops + waste top). */
function foundationOpportunities(state: SolitaireState): number {
  let count = 0;
  const columns = state.tableau ?? [];
  for (let column = 0; column < columns.length; column += 1) {
    const top = tableauTop(state, column);
    if (!top?.faceUp || !top.card) continue;
    if (top.card.rank === foundationExpects(state, top.card.suit)) count += 1;
  }
  const wasteTop = state.waste?.[state.waste.length - 1];
  if (wasteTop && wasteTop.rank === foundationExpects(state, wasteTop.suit)) count += 1;
  return count;
}

/**
 * Whether a King-led run could use an empty column right now.
 *
 * A lone King shuffled onto an empty column changes nothing, so the run must be
 * at least two cards — this is the "a sequence could be relocated" signal, not
 * merely "a legal move exists".
 */
function hasKingPlacement(state: SolitaireState): boolean {
  const columns = state.tableau ?? [];
  if (!columns.some((column) => column.length === 0)) return false;
  for (let index = 0; index < columns.length; index += 1) {
    for (const pile of columns[index]) {
      if (!pile.faceUp || !pile.card || pile.card.rank !== KING) continue;
      const run = faceUpRunFrom(state, index, pile.card);
      if (run && run.length >= 2) return true;
    }
  }
  return false;
}

/** True when applying `move` leaves its source tableau column empty. */
function leavesColumnEmpty(
  before: SolitaireState,
  after: SolitaireState,
  move: SolitaireMove
): boolean {
  if (move.kind !== "tableau-to-foundation" && move.kind !== "tableau-to-tableau") {
    return false;
  }
  const from = move.fromColumn;
  if ((before.tableau?.[from]?.length ?? 0) === 0) return false;
  return (after.tableau?.[from]?.length ?? -1) === 0;
}

// ──────────────────────────────────────────────────────────────────────────
// Candidate scoring and the budgeted deeper comparison
// ──────────────────────────────────────────────────────────────────────────

type AppliedScore = {
  move: SolitaireMove;
  key: string;
  score: number;
};

/** A stable identity for a move, used for tie-breaking and de-duplication. */
function moveKey(move: SolitaireMove): string {
  switch (move.kind) {
    case "draw":
      return "draw";
    case "waste-to-foundation":
      return `waste-to-foundation:${move.suit}`;
    case "waste-to-tableau":
      return `waste-to-tableau:${move.toColumn}`;
    case "tableau-to-foundation":
      return `tableau-to-foundation:${move.fromColumn}:${move.card.suit}${move.card.rank}:${move.suit}`;
    case "tableau-to-tableau":
      return `tableau-to-tableau:${move.fromColumn}:${move.card.suit}${move.card.rank}:${move.toColumn}`;
    case "foundation-to-tableau":
      return `foundation-to-tableau:${move.suit}:${move.toColumn}`;
    default:
      return "unknown";
  }
}

/** Apply a move and score the resulting visible position, or null if refused. */
function applyAndScore(
  state: SolitaireState,
  move: SolitaireMove,
  memo: Map<string, number>
): AppliedScore | null {
  const applied = applyMove({ state, move });
  if (!applied.ok) return null;
  const after = applied.state as SolitaireState;
  return {
    move,
    key: moveKey(move),
    score: scoreWithMemo(after, memo),
  };
}

/**
 * A discount-weighted two-ply value for one move.
 *
 * Used ONLY on ambiguous decisions, under one shared node budget for the whole
 * game. It stops at anything that would look past the player's information
 * horizon — a draw, a foundation pull, or a move that turns over a hidden card —
 * exactly like the bot evaluator it borrows the concept from. That is why a
 * deeper comparison can sharpen a positive rating but never manufacture a
 * criticism out of hindsight.
 */
function deepScore(
  state: SolitaireState,
  move: SolitaireMove,
  depth: number,
  budget: { nodes: number; max: number },
  memo: Map<string, number>,
  beamWidth: number
): number | null {
  const applied = applyMove({ state, move });
  if (!applied.ok) return null;
  const after = applied.state as SolitaireState;
  const base = scoreWithMemo(after, memo);
  const revealed = ((applied as { revealed?: Card[] }).revealed ?? []).length;

  if (
    depth <= 0 ||
    budget.nodes >= budget.max ||
    move.kind === "draw" ||
    move.kind === "foundation-to-tableau" ||
    revealed > 0 ||
    after.completed
  ) {
    return base;
  }

  // Beam the children by their own one-ply value BEFORE recursing, so a wide
  // board cannot multiply the work: the budget is spent on the plausible
  // continuations only, exactly like the bot evaluator this borrows from.
  const children = legalMoves(after)
    .filter((candidate) => candidate.kind !== "draw" && candidate.kind !== "foundation-to-tableau")
    .map((candidate) => {
      const scored = applyAndScore(after, candidate, memo);
      return scored ? { move: candidate as SolitaireMove, scored } : null;
    })
    .filter((row): row is { move: SolitaireMove; scored: AppliedScore } => row !== null)
    .sort((a, b) => b.scored.score - a.scored.score || a.scored.key.localeCompare(b.scored.key))
    .slice(0, Math.max(1, beamWidth));

  let bestChild = 0;
  for (const child of children) {
    if (budget.nodes >= budget.max) break;
    budget.nodes += 1;
    const childScore = deepScore(after, child.move, depth - 1, budget, memo, beamWidth);
    if (childScore !== null) bestChild = Math.max(bestChild, childScore);
  }
  return base + Math.round(DEEP_PLANNING_WEIGHT * bestChild);
}

